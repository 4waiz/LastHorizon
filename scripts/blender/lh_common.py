_MATERIAL_CACHE = {}


def mk_material(key):
    """Create (or fetch) a shared material for a palette key or raw hex."""
    if key in _MATERIAL_CACHE:
        return _MATERIAL_CACHE[key]

    hexcode = PALETTE.get(key, key)
    r, g, b = hex_to_srgb(hexcode)
    lin = (srgb_to_linear(r), srgb_to_linear(g), srgb_to_linear(b), 1.0)

    mat = bpy.data.materials.new(name=key if key in PALETTE else "c" + hexcode.lstrip("#"))
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    if bsdf:
        bsdf.inputs["Base Color"].default_value = lin
        bsdf.inputs["Roughness"].default_value = 0.85
        bsdf.inputs["Metallic"].default_value = 0.0
    mat.diffuse_color = lin
    _MATERIAL_CACHE[key] = mat
    return mat


def clear_material_cache():
    _MATERIAL_CACHE.clear()


