"""
LastHorizon — shared Blender helpers for procedural asset generation.

Every asset in `public/assets/models/` is generated by the scripts in this
folder. Nothing is downloaded, imported or traced from any third party source.

Run inside Blender (via Blender MCP or `blender --background --python`):

    exec(open("<repo>/scripts/blender/build_all.py").read())

Conventions
-----------
* Blender is Z-up; the glTF exporter converts to Y-up for Three.js.
* Characters and directional props face **-Y in Blender**, which becomes
  **+Z in glTF/Three.js**. `rotation.y = atan2(dir.x, dir.z)` then works.
* Colours in `PALETTE` are authored in sRGB and converted to linear on
  material creation so the exported baseColorFactor renders as authored.
* One material per colour, shared across every object, so the Three.js
  AssetManager can collapse them into a small set of toon materials.
"""

