def reset_scene():
    """Wipe every datablock so each asset build starts from a clean slate."""
    if bpy.context.object and bpy.context.object.mode != "OBJECT":
        bpy.ops.object.mode_set(mode="OBJECT")

    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)

    # Actions are kept alive by fake users; drop those first or a rebuild
    # accumulates "Walk.001", "Walk.002", ... and the exporter emits them all.
    for act in bpy.data.actions:
        act.use_fake_user = False

    for coll in (bpy.data.objects, bpy.data.meshes, bpy.data.materials,
                 bpy.data.armatures, bpy.data.actions, bpy.data.curves):
        for block in list(coll):
            if block.users == 0:
                coll.remove(block)

    clear_material_cache()
    bpy.context.scene.frame_set(1)


