def bevel(obj, width=0.012, segments=1, angle=math.radians(50)):
    m = obj.modifiers.new("bevel", "BEVEL")
    m.width = width
    m.segments = segments
    m.limit_method = "ANGLE"
    m.angle_limit = angle
    m.harden_normals = False
    return obj


def apply_modifiers(obj):
    bpy.context.view_layer.objects.active = obj
    for m in list(obj.modifiers):
        try:
            bpy.ops.object.modifier_apply(modifier=m.name)
        except RuntimeError:
            obj.modifiers.remove(m)
    return obj


def rotate_verts(obj, angles, pivot=(0, 0, 0)):
    """Bake an XYZ rotation (radians) into the mesh, about a world pivot.

    Setting `obj.rotation_euler` pivots about the object origin, which for
    every primitive here sits at the world origin — so a part authored at
    z=4 would swing metres away. Baking into the vertices avoids that trap.
    """
    r = Euler(angles, "XYZ").to_matrix()
    piv = Vector(pivot)
    for v in obj.data.vertices:
        v.co = r @ (v.co - piv) + piv
    return obj


def transform(obj, loc=None, rot=None, scale=None):
    if loc is not None:
        obj.location = loc
    if rot is not None:
        obj.rotation_euler = Euler(rot, "XYZ")
    if scale is not None:
        obj.scale = scale if hasattr(scale, "__len__") else (scale, scale, scale)
    return obj


def join_objects(objs, name):
    """Join a list of mesh objects into one, applying modifiers first."""
    objs = [o for o in objs if o is not None]
    if not objs:
        return None
    bpy.ops.object.select_all(action="DESELECT")
    for o in objs:
        apply_modifiers(o)
    for o in objs:
        o.select_set(True)
    bpy.context.view_layer.objects.active = objs[0]
    if len(objs) > 1:
        bpy.ops.object.join()
    result = bpy.context.view_layer.objects.active
    result.name = name
    result.data.name = name + "_mesh"
    bpy.ops.object.select_all(action="DESELECT")
    return result


def set_origin_to(obj, point=(0, 0, 0)):
    """Move the mesh so that `point` (world) becomes the object origin."""
    mw = obj.matrix_world.copy()
    offset = Vector(point)
    me = obj.data
    for v in me.vertices:
        v.co = mw @ v.co - offset
    obj.matrix_world = Matrix.Translation(offset)
    return obj


def recalc_normals(obj):
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    bpy.ops.object.mode_set(mode="EDIT")
    bpy.ops.mesh.select_all(action="SELECT")
    bpy.ops.mesh.normals_make_consistent(inside=False)
    bpy.ops.object.mode_set(mode="OBJECT")
    bpy.ops.object.select_all(action="DESELECT")
    return obj


def tri_count(obj):
    obj.data.calc_loop_triangles()
    return len(obj.data.loop_triangles)


