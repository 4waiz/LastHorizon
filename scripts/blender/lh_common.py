def _finish(obj, mat_key, flat=True):
    if mat_key is not None:
        obj.data.materials.append(mk_material(mat_key))
    if flat:
        for poly in obj.data.polygons:
            poly.use_smooth = False
    return obj


def mesh_from(name, verts, faces, mat_key=None, flat=True):
    me = bpy.data.meshes.new(name)
    me.from_pydata(verts, [], faces)
    me.update()
    obj = bpy.data.objects.new(name, me)
    bpy.context.collection.objects.link(obj)
    return _finish(obj, mat_key, flat)


def box(name, size, center=(0, 0, 0), mat_key=None):
    """Axis-aligned box. `size` is the full extent on each axis."""
    sx, sy, sz = size[0] / 2.0, size[1] / 2.0, size[2] / 2.0
    cx, cy, cz = center
    v = [
        (cx - sx, cy - sy, cz - sz), (cx + sx, cy - sy, cz - sz),
        (cx + sx, cy + sy, cz - sz), (cx - sx, cy + sy, cz - sz),
        (cx - sx, cy - sy, cz + sz), (cx + sx, cy - sy, cz + sz),
        (cx + sx, cy + sy, cz + sz), (cx - sx, cy + sy, cz + sz),
    ]
    # Wound counter-clockwise seen from outside so normals point out and the
    # meshes survive backface culling in Three.js.
    f = [(3, 2, 1, 0), (4, 5, 6, 7), (0, 1, 5, 4),
         (1, 2, 6, 5), (2, 3, 7, 6), (3, 0, 4, 7)]
    return mesh_from(name, v, f, mat_key)


def wedge(name, size, center=(0, 0, 0), mat_key=None, axis="y"):
    """Right-triangle prism — ramps, shed roofs, awnings.

    axis="y": full height at -Y, sloping down toward +Y.
    axis="x": full height at -X, sloping down toward +X.
    """
    sx, sy, sz = size[0] / 2.0, size[1] / 2.0, size[2] / 2.0
    cx, cy, cz = center
    base = [
        (cx - sx, cy - sy, cz - sz), (cx + sx, cy - sy, cz - sz),
        (cx + sx, cy + sy, cz - sz), (cx - sx, cy + sy, cz - sz),
    ]
    if axis == "y":
        v = base + [(cx - sx, cy - sy, cz + sz), (cx + sx, cy - sy, cz + sz)]
        f = [(3, 2, 1, 0), (0, 1, 5, 4), (4, 5, 2, 3), (0, 4, 3), (1, 2, 5)]
    else:
        v = base + [(cx - sx, cy - sy, cz + sz), (cx - sx, cy + sy, cz + sz)]
        f = [(3, 2, 1, 0), (0, 4, 5, 3), (5, 4, 1, 2), (0, 1, 4), (3, 5, 2)]
    return mesh_from(name, v, f, mat_key)


def gable_roof(name, width, depth, height, center=(0, 0, 0), overhang=0.0,
               ridge_along="y", mat_key=None, thickness=0.0):
    """Classic pitched roof. Ridge runs along Y (default) or X."""
    cx, cy, cz = center
    w = width / 2.0 + overhang
    d = depth / 2.0 + overhang
    if ridge_along == "y":
        v = [
            (cx - w, cy - d, cz), (cx + w, cy - d, cz),
            (cx + w, cy + d, cz), (cx - w, cy + d, cz),
            (cx, cy - d, cz + height), (cx, cy + d, cz + height),
        ]
        f = [(0, 1, 2, 3), (0, 4, 5, 3), (1, 5, 4), (2, 5, 1), (0, 3, 5, 4)]
        f = [(3, 2, 1, 0), (0, 1, 4), (1, 2, 5, 4), (2, 3, 5), (3, 0, 4, 5)]
    else:
        v = [
            (cx - w, cy - d, cz), (cx + w, cy - d, cz),
            (cx + w, cy + d, cz), (cx - w, cy + d, cz),
            (cx - w, cy, cz + height), (cx + w, cy, cz + height),
        ]
        f = [(3, 2, 1, 0), (0, 1, 5, 4), (1, 2, 5), (2, 3, 4, 5), (3, 0, 4)]
    obj = mesh_from(name, v, f, mat_key)
    if thickness > 0:
        sol = obj.modifiers.new("solid", "SOLIDIFY")
        sol.thickness = thickness
        sol.offset = -1
    return obj


def cylinder(name, radius, height, verts=12, center=(0, 0, 0), mat_key=None,
             radius_top=None, cap=True):
    rt = radius if radius_top is None else radius_top
    cx, cy, cz = center
    v, f = [], []
    for i in range(verts):
        a = 2 * math.pi * i / verts
        v.append((cx + math.cos(a) * radius, cy + math.sin(a) * radius, cz))
    for i in range(verts):
        a = 2 * math.pi * i / verts
        v.append((cx + math.cos(a) * rt, cy + math.sin(a) * rt, cz + height))
    for i in range(verts):
        j = (i + 1) % verts
        f.append((i, j, verts + j, verts + i))
    if cap:
        f.append(tuple(range(verts - 1, -1, -1)))
        f.append(tuple(range(verts, verts * 2)))
    return mesh_from(name, v, f, mat_key)


def tube_along(name, points, radius, verts=8, mat_key=None, taper=None):
    """Sweep a circular profile along a polyline — poles, cables, branches."""
    v, f = [], []
    n = len(points)
    for idx, p in enumerate(points):
        p = Vector(p)
        if idx < n - 1:
            fwd = (Vector(points[idx + 1]) - p).normalized()
        else:
            fwd = (p - Vector(points[idx - 1])).normalized()
        if idx > 0:
            prev = (p - Vector(points[idx - 1])).normalized()
            fwd = (fwd + prev).normalized()
        up = Vector((0, 0, 1))
        if abs(fwd.dot(up)) > 0.99:
            up = Vector((1, 0, 0))
        side = fwd.cross(up).normalized()
        up2 = side.cross(fwd).normalized()
        r = radius if taper is None else radius * taper(idx / max(1, n - 1))
        for i in range(verts):
            # negative sweep so the profile runs counter-clockwise about the
            # forward axis, which makes the quad windings below face outward
            a = -2 * math.pi * i / verts
            v.append(tuple(p + side * (math.cos(a) * r) + up2 * (math.sin(a) * r)))
    for s in range(n - 1):
        for i in range(verts):
            j = (i + 1) % verts
            a0 = s * verts + i
            b0 = s * verts + j
            a1 = (s + 1) * verts + i
            b1 = (s + 1) * verts + j
            f.append((a0, b0, b1, a1))
    f.append(tuple(range(verts - 1, -1, -1)))
    f.append(tuple(range((n - 1) * verts, n * verts)))
    return mesh_from(name, v, f, mat_key)


def ico_blob(name, radius, center=(0, 0, 0), subdiv=2, jitter=0.18, seed=0,
             scale=(1, 1, 1), mat_key=None, flatten_bottom=None):
    """Faceted organic mass — tree canopies, bushes, rocks, clouds."""
    rng = random.Random(seed)
    bm = bmesh.new()
    bmesh.ops.create_icosphere(bm, subdivisions=subdiv, radius=radius)
    for vert in bm.verts:
        d = vert.co.normalized()
        vert.co += d * (rng.uniform(-jitter, jitter) * radius)
        vert.co.x *= scale[0]
        vert.co.y *= scale[1]
        vert.co.z *= scale[2]
        if flatten_bottom is not None and vert.co.z < flatten_bottom:
            vert.co.z = flatten_bottom + (vert.co.z - flatten_bottom) * 0.15
    me = bpy.data.meshes.new(name)
    bm.to_mesh(me)
    bm.free()
    obj = bpy.data.objects.new(name, me)
    bpy.context.collection.objects.link(obj)
    obj.location = center
    return _finish(obj, mat_key)


def plane(name, width, depth, center=(0, 0, 0), mat_key=None):
    w, d = width / 2.0, depth / 2.0
    cx, cy, cz = center
    v = [(cx - w, cy - d, cz), (cx + w, cy - d, cz), (cx + w, cy + d, cz), (cx - w, cy + d, cz)]
    return mesh_from(name, v, [(0, 1, 2, 3)], mat_key)


