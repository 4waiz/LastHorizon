def export_glb(objs, filename, animations=False):
    """Export the given objects to public/assets/models/<filename>."""
    ensure_model_dir()
    path = os.path.join(MODEL_DIR, filename).replace("\\", "/")

    if bpy.context.object and bpy.context.object.mode != "OBJECT":
        bpy.ops.object.mode_set(mode="OBJECT")
    bpy.ops.object.select_all(action="DESELECT")
    objs = [o for o in objs if o is not None]
    for o in objs:
        o.select_set(True)
    bpy.context.view_layer.objects.active = objs[0]

    kwargs = dict(
        filepath=path,
        export_format="GLB",
        use_selection=True,
        export_yup=True,
        export_apply=not animations,
        export_normals=True,
        export_tangents=False,
        export_materials="EXPORT",
        export_cameras=False,
        export_lights=False,
        export_extras=False,
        export_texcoords=True,
    )
    if animations:
        kwargs.update(
            export_animations=True,
            export_animation_mode="ACTIONS",
            export_skins=True,
            export_def_bones=False,
            export_bake_animation=False,
            export_optimize_animation_size=True,
            export_force_sampling=False,
            export_frame_range=False,
            export_anim_slide_to_zero=False,
        )
    else:
        kwargs.update(export_animations=False, export_skins=False)

    bpy.ops.export_scene.gltf(**kwargs)
    size = os.path.getsize(path)
    return {"file": filename, "path": path, "kb": round(size / 1024.0, 1)}


def report(entries):
    total = sum(e["kb"] for e in entries)
    lines = ["%-26s %8.1f KB" % (e["file"], e["kb"]) for e in entries]
    lines.append("%-26s %8.1f KB" % ("TOTAL", total))
    return "\n".join(lines)
