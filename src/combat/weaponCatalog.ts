/**
 * Four entries, and one of them is your hands.
 *
 * The numbers are balanced against a single question: **how many shots does a
 * calm person need to stop somebody, and how many does a panicking one waste?**
 * Composure is 0..1 and an unarmed shove takes 0.34, so three shoves settle an
 * ordinary argument. That is the yardstick everything else is measured against.
 *
 * | | Shots to stop, point-blank | At full range |
 * | --- | --- | --- |
 * | shove | 3 | n/a |
 * | pistol | 2 | 3 |
 * | shotgun | 1 | 3 |
 * | carbine | 2 | 2 |
 *
 * The shotgun is the only one-shot stopper and it is deliberately the worst
 * weapon in the game at anything past a corridor: eight pellets in a 9-degree
 * cone means most of them miss at twenty metres. The carbine is the opposite —
 * it barely cares about distance and is the loudest thing here, so using it
 * anywhere near people is how a quiet crime becomes a chase.
 *
 * **Nothing in this table is a real product.** The names are descriptive, the
 * models are generated by `scripts/blender/build_weapons.py`, and there is no
 * brand, marking or silhouette copied from anything.
 */

