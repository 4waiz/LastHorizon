export const WEAPONS: readonly WeaponDef[] = [UNARMED, PISTOL, SHOTGUN, CARBINE];

const BY_ID = new Map(WEAPONS.map((w) => [w.id, w]));

export function weaponDef(id: string): WeaponDef | null {
  return BY_ID.get(id as WeaponId) ?? null;
}

/** Everything that is not your hands. What the adult gate actually covers. */
export const FIREARM_IDS: readonly WeaponId[] = WEAPONS.filter(
  (w) => w.weaponClass !== 'unarmed',
).map((w) => w.id);

/** Ammunition items the catalogue needs, so `Inventory` and this cannot drift. */
export const AMMO_ITEM_IDS: readonly string[] = WEAPONS.map((w) => w.ammoItemId).filter(
  (id): id is string => id !== null,
);
